#!/usr/bin/env python3
"""Generate ~/.config/just/mail.just from the Himalaya account names.

Public-repo safe: reads the local ~/.config/himalaya/config.toml and writes a
local file (0600). Nothing generated here is committed. No passwords are read.

Recipes:
  <account>   one per Himalaya account (e.g. example-mail, example-spam)
  <domain>    one per account prefix before the first "-": the personal
              mailbox if exactly one local-part is not mail/spam/admin,
              otherwise <domain>-mail. Accounts without "-" (icloud, gmail)
              only get their own name.
  <alias>     optional extra names from a local aliases file (default
              ~/.config/just/mail-aliases, not in git), one `alias = account`
              per line, `#` comments allowed. See scripts/just-mail-aliases.example.
"""
from __future__ import annotations

import argparse
import os
import re
import tomllib
from collections import defaultdict
from pathlib import Path

ROLE = {"mail", "spam", "admin"}
IDENT = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]*$")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", type=Path, default=Path.home() / ".config/himalaya/config.toml")
    ap.add_argument("--out", type=Path, default=Path.home() / ".config/just/mail.just")
    ap.add_argument("--aliases", type=Path, default=Path.home() / ".config/just/mail-aliases")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    accounts = tomllib.loads(a.config.read_text()).get("accounts", {})
    emails = {name: acc.get("email", "") for name, acc in accounts.items() if IDENT.match(name)}
    groups: dict[str, list[str]] = defaultdict(list)
    for name in emails:
        if "-" in name:
            groups[name.split("-", 1)[0]].append(name)

    lines = [
        "# Generated by scripts/just-mail-gen.py from ~/.config/himalaya/config.toml.",
        "# Local only, do not commit. Re-run the script after changing Himalaya accounts.",
        "",
    ]

    def recipe(rname: str, account: str, kind: str) -> None:
        lines.append(f"# {kind}: {emails[account]} (himalaya account {account})")
        lines.append(f"{rname} *args:")
        lines.append(f'    @"{{{{justfile_directory()}}}}/himalaya-open.sh" {account} "$@"')
        lines.append("")

    for domain in sorted(groups):
        if domain in emails:
            continue  # an account already has that bare name
        members = sorted(groups[domain])
        personal = [m for m in members if m.split("-", 1)[1] not in ROLE]
        primary = personal[0] if len(personal) == 1 else (f"{domain}-mail" if f"{domain}-mail" in members else members[0])
        recipe(domain, primary, "domain")
    for name in sorted(emails):
        recipe(name, name, "mail")

    taken = set(emails) | set(groups) | {"default", "mail"}
    if a.aliases.is_file():
        for n, raw in enumerate(a.aliases.read_text().splitlines(), 1):
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            alias, _, account = (x.strip() for x in line.partition("="))
            if not IDENT.match(alias) or account not in emails:
                raise SystemExit(f"{a.aliases}:{n}: need `alias = account` with an existing Himalaya account")
            if alias in taken:
                raise SystemExit(f"{a.aliases}:{n}: alias {alias!r} clashes with an existing recipe")
            taken.add(alias)
            recipe(alias, account, "alias")

    text = "\n".join(lines)
    if a.dry_run:
        print(text)
        return
    a.out.parent.mkdir(parents=True, exist_ok=True)
    tmp = a.out.with_suffix(".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(text)
    os.replace(tmp, a.out)
    print(f"mail.just: wrote {a.out} ({len(groups)} domains, {len(emails)} accounts)")


if __name__ == "__main__":
    main()
